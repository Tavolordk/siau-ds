/**
 * Visual variant of an interactive component.
 *
 * - `primary`: main call to action (dark, filled).
 * - `secondary`: secondary action (outlined / soft).
 * - `tertiary`: low-emphasis action (ghost / text-like).
 * - `danger`: destructive action.
 */
export type UiVariant = 'primary' | 'secondary' | 'tertiary' | 'danger';